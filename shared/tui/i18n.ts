const tables: Record<DocsLanguage, Record<TextKey, string>> = { "pt-BR": pt, en };

/** Every text key, for tests that look for a key shown instead of its text. */
export const TEXT_KEYS = Object.keys(en) as TextKey[];

let current: DocsLanguage | undefined;

const isLanguage = (v: unknown): v is DocsLanguage => v === "pt-BR" || v === "en";

/**
 * Resolves the TUI language: SETUPVIBE_LANG when set (it pins the language,
 * as in automation and tests), then `tui.language` from settings.json, whose
 * default is Portuguese.
 */
export function resolveTuiLanguage(env: Record<string, string | undefined> = process.env, saved: () => unknown = savedLanguage): DocsLanguage {
  if (isLanguage(env.SETUPVIBE_LANG)) return env.SETUPVIBE_LANG;
  const fromSettings = saved();
  return isLanguage(fromSettings) ? fromSettings : "pt-BR";
}

function savedLanguage(): unknown {
  try {
    return getPath(readSettings(), "tui.language");
  } catch {
    return undefined;
  }
}

/** Language of the TUI, cached until `resetTuiLanguage` or `setTuiLanguage`. */
export function tuiLanguage(): DocsLanguage {
  return (current ??= resolveTuiLanguage());
}

/** Forgets the cached language; the next call reads settings and environment again. */
export function resetTuiLanguage(): void {
  current = undefined;
}

/** Switches the TUI language and saves it in settings.json (best effort). */
export function setTuiLanguage(language: DocsLanguage): void {
  current = language;
  try {
    const settings = readSettings();
    setPath(settings, "tui.language", language);
    writeSettings(settings);
  } catch {
    // A read-only settings file keeps the choice for this session only.
  }
}

/** True when the key has a text, for optional texts such as module subtitles. */
export function hasText(key: string): key is TextKey {
  return key in tables.en;
}

/** The other language, for the toggle. */
export function otherLanguage(language: DocsLanguage = tuiLanguage()): DocsLanguage {
  return language === "pt-BR" ? "en" : "pt-BR";
}

/** Text for a key, with `{name}` placeholders filled in. */
export function tr(key: TextKey, values: Record<string, string | number> = {}, language: DocsLanguage = tuiLanguage()): string {
  // A key missing from the table (a module without a subtitle, for example) falls back to English, then to the key.
  const text = tables[language][key] ?? tables.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k: string) => String(values[k] ?? `{${k}}`));
}

/** A doctor finding as the TUI shows it: what the CLI reports, in the TUI language. */
interface TranslatableFinding {
  id: string;
  level: string;
  text: string;
  fix?: string;
  params?: Record<string, string>;
}

/** Key of a finding: `other-<item>` findings share one text. */
const findingKey = (f: TranslatableFinding) => (f.id.startsWith("other-") ? "other" : f.id);

/** Text of a finding in the TUI language; the CLI text when there is no translation. */
export function findingText(f: TranslatableFinding): string {
  const key = `finding.${findingKey(f)}.${f.level}`;
  return hasText(key) ? tr(key, f.params ?? {}) : f.text;
}

/** Fix of a finding: prose fixes are translated, commands stay as they are. */
export function findingFix(f: TranslatableFinding): string | undefined {
  const key = `finding.${findingKey(f)}.fix`;
  return f.fix && hasText(key) ? tr(key, f.params ?? {}) : f.fix;
}

/** Tailscale backend state (Running, Stopped, NeedsLogin…) in the TUI language. */
export function tailscaleState(state: string): string {
  const key = `ts.state.${state}`;
  return hasText(key) ? tr(key) : state || "?";
}
