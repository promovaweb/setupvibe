const tables: Record<DocsLanguage, Record<TextKey, string>> = { "pt-BR": pt, en };

/** Language of the TUI. */
export function tuiLanguage(): DocsLanguage {
  return docsLanguage();
}

/** Text for a key, with `{name}` placeholders filled in. */
export function tr(key: TextKey, values: Record<string, string | number> = {}, language: DocsLanguage = tuiLanguage()): string {
  return tables[language][key].replace(/\{(\w+)\}/g, (_, k: string) => String(values[k] ?? `{${k}}`));
}
